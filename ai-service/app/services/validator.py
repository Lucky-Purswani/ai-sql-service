# sqlfluff is a professional-grade SQL linter and parser.
# It can convert a raw SQL string into an Abstract Syntax Tree (AST),
# which is a structured representation of the query's logical meaning.
import sqlfluff


def is_safe_sql(sql_query: str) -> dict:
    """
    Validates that an AI-generated SQL query is safe to execute (read-only).

    WHY DO WE NEED THIS if we already told the LLM to only write SELECT?
    Because LLMs can hallucinate or be manipulated via Prompt Injection.
    A malicious user could ask: "Show me users, then also DELETE all records."
    The LLM might comply. This validator is the hard security gate that catches that.

    WHY sqlfluff instead of just checking `if "DELETE" in sql`?
    String matching is dangerously naive. Consider:
        SELECT * FROM employees WHERE name = 'DELETE me';
    A string check would block this VALID and SAFE query just because it contains "DELETE".
    sqlfluff parses the actual SQL grammar and understands that "DELETE me" is a string
    value, not a SQL command, so it correctly allows it.

    Args:
        sql_query: The raw SQL string generated by the LLM.

    Returns:
        A dictionary: {"is_valid": True, "reason": None}
                   or {"is_valid": False, "reason": "Blocked: ..."}
    """
    try:
        # sqlfluff.parse() converts the raw SQL string into an AST (Abstract Syntax Tree).
        # An AST is a nested dictionary representing the query's logical structure.
        # dialect="postgres" tells sqlfluff to use PostgreSQL grammar rules.
        # Example output for "SELECT 1":
        # {"file": {"statement": {"select_statement": {"select_clause": {"keyword": "SELECT", ...}}}}}
        parsed = sqlfluff.parse(sql_query, dialect="postgres")
    except Exception as e:
        # If sqlfluff itself can't understand the SQL, it's definitely not valid.
        return {"is_valid": False, "reason": "Blocked: Invalid SQL syntax."}

    # The set of AST node keys that represent dangerous, write/destructive operations.
    # These match the exact key names that sqlfluff uses in its output dictionary.
    dangerous_types = {
        "delete_statement",    # DELETE FROM ...
        "update_statement",    # UPDATE ... SET ...
        "insert_statement",    # INSERT INTO ...
        "drop_statement",      # DROP TABLE ...
        "alter_statement",     # ALTER TABLE ...
        "truncate_statement",  # TRUNCATE TABLE ...
        "create_statement",    # CREATE TABLE ...
        "grant_statement",     # GRANT permissions ...
        "revoke_statement",    # REVOKE permissions ...
    }

    # We use a flag to confirm the query contains at least one SELECT.
    # A query with NO dangerous operations but also NO SELECT (e.g., empty string) is also blocked.
    has_select = False

    # check_node() is a RECURSIVE function that walks the entire AST tree.
    # Recursive means it calls itself on nested data until it reaches the bottom.
    # We need this because the AST is a deeply nested structure (dicts inside dicts inside lists).
    def check_node(node):
        nonlocal has_select  # Allow this inner function to modify the outer `has_select` variable

        if isinstance(node, dict):
            # Each key in the dict is an AST node type (e.g., "select_statement", "keyword")
            for key, value in node.items():
                # SECURITY CHECK: If this node is a dangerous operation type → block immediately
                if key in dangerous_types:
                    return f"Blocked: Contains dangerous operation ({key.replace('_statement', '').upper()})"

                # CONFIRMATION: Found a SELECT. Mark it so we know the query is not empty/malformed.
                # "with_compound_statement" covers CTEs: WITH ... AS (...) SELECT ...
                if key == "select_statement" or key == "with_compound_statement":
                    has_select = True

                # RECURSE: Go deeper into the nested value and check everything inside it too.
                error = check_node(value)
                if error:
                    return error  # Immediately propagate any error found deep in the tree

        elif isinstance(node, list):
            # Some AST nodes contain a list of children — check each one.
            for item in node:
                error = check_node(item)
                if error:
                    return error

        # Return None if no issues found at this level (the recursion base case).
        return None

    # Start the recursive walk from the root of the parsed AST dictionary.
    error_reason = check_node(parsed)

    # If any dangerous operation was found during the walk, return the error.
    if error_reason:
        return {"is_valid": False, "reason": error_reason}

    # If we walked the entire tree and never found a SELECT, the query is invalid.
    if not has_select:
        return {"is_valid": False, "reason": "Blocked: No SELECT statement found"}

    # All checks passed — the query is safe to execute.
    return {"is_valid": True, "reason": None}
